// BOAS-VINDAS DO BOT DA CLIENTE: quando o bot conecta, ele manda no privado
// da dona, no idioma que ela escolheu, o passo a passo do menu dono: deixar
// o bot pronto no grupo, trocar imagem do menu, nome, foto e prefixo, colocar
// subdono. Sem link e sem nada do Aurora, do site ou do dono da casa.
export function textoBoasVindas(marca, prefixo = '#') {
  const p = String(prefixo || '#')
  const nome = String(marca?.nome || 'Bot')
  const dona = String(marca?.donoNome || '').trim()
  const textos = {
    pt: [
      `👋 Olá${dona ? ', ' + dona : ''}! Seu bot *${nome}* está conectado.`,
      'Aqui vai o passo a passo para começar. Os comandos abaixo só funcionam para você (e para os subdonos que você colocar).',
      '',
      '*1. Deixar o bot pronto no grupo*',
      '• Adicione o bot no grupo e deixe ele como *admin*.',
      `• No grupo, mande *${p}rgaluguel*. O bot só responde nos grupos registrados.`,
      '',
      '*2. Imagem do menu*',
      `• Mande uma foto ou vídeo com a legenda *${p}fotomenu* (ou responda a uma foto com *${p}fotomenu*).`,
      '• Para trocar a imagem, é só fazer de novo com outra.',
      '',
      '*3. Nome e foto do bot*',
      `• Nome: *${p}nomebot Novo Nome*`,
      `• Foto de perfil: mande uma foto com a legenda *${p}fotobot* (ou responda a uma foto com *${p}fotobot*).`,
      '',
      '*4. Prefixo (o símbolo antes dos comandos)*',
      `• *${p}setprefix !* troca para *!*. Depois os comandos ficam *!menu*, *!fotomenu*...`,
      '• O */* sempre funciona também, caso você esqueça o prefixo.',
      '',
      '*5. Subdonos (pessoas que te ajudam)*',
      `• Colocar: *${p}addsubdono @pessoa* (ou o número com DDI)`,
      `• Tirar: *${p}delsubdono @pessoa*`,
      `• Ver a lista: *${p}subdonos*`,
      '',
      '*6. Free Fire e idioma*',
      `• Liberar o autolike para alguém: *${p}addvip @pessoa*`,
      `• Limite de IDs por pessoa: *${p}configurarff 3* (*0* = sem limite)`,
      `• Idioma do grupo: *${p}idioma pt*, *${p}idioma es* ou *${p}idioma en*`,
      '',
      '*7. Menus*',
      `• *${p}menudono*: todos os seus comandos de dono.`,
      `• *${p}menu*: o menu que todo mundo vê.`,
      '',
      'Imagem do menu, nome, foto, prefixo e subdonos valem só para o seu bot. Limite de IDs e idioma valem só para o grupo onde você mandou o comando.'
    ],
    es: [
      `👋 ¡Hola${dona ? ', ' + dona : ''}! Tu bot *${nome}* está conectado.`,
      'Aquí tienes el paso a paso para empezar. Estos comandos solo funcionan para ti (y para los subdueños que pongas).',
      '',
      '*1. Dejar el bot listo en el grupo*',
      '• Agrega el bot al grupo y hazlo *admin*.',
      `• En el grupo, envía *${p}rgaluguel*. El bot solo responde en los grupos registrados.`,
      '',
      '*2. Imagen del menú*',
      `• Envía una foto o video con el texto *${p}fotomenu* (o responde a una foto con *${p}fotomenu*).`,
      '• Para cambiar la imagen, solo hazlo de nuevo con otra.',
      '',
      '*3. Nombre y foto del bot*',
      `• Nombre: *${p}nomebot Nuevo Nombre*`,
      `• Foto de perfil: envía una foto con el texto *${p}fotobot* (o responde a una foto con *${p}fotobot*).`,
      '',
      '*4. Prefijo (el símbolo antes de los comandos)*',
      `• *${p}setprefix !* lo cambia a *!*. Después los comandos quedan *!menu*, *!fotomenu*...`,
      '• El */* siempre funciona también, por si olvidas el prefijo.',
      '',
      '*5. Subdueños (personas que te ayudan)*',
      `• Poner: *${p}addsubdono @persona* (o el número con código de país)`,
      `• Quitar: *${p}delsubdono @persona*`,
      `• Ver la lista: *${p}subdonos*`,
      '',
      '*6. Free Fire e idioma*',
      `• Dar el autolike a alguien: *${p}addvip @persona*`,
      `• Límite de IDs por persona: *${p}configurarff 3* (*0* = sin límite)`,
      `• Idioma del grupo: *${p}idioma pt*, *${p}idioma es* o *${p}idioma en*`,
      '',
      '*7. Menús*',
      `• *${p}menudono*: todos tus comandos de dueño.`,
      `• *${p}menu*: el menú que ve todo el mundo.`,
      '',
      'Imagen del menú, nombre, foto, prefijo y subdueños valen solo para tu bot. Límite de IDs e idioma valen solo para el grupo donde enviaste el comando.'
    ],
    en: [
      `👋 Hi${dona ? ', ' + dona : ''}! Your bot *${nome}* is connected.`,
      'Here is the step by step to get started. These commands only work for you (and for the sub-owners you add).',
      '',
      '*1. Get the bot ready in the group*',
      '• Add the bot to the group and make it *admin*.',
      `• In the group, send *${p}rgaluguel*. The bot only answers in registered groups.`,
      '',
      '*2. Menu image*',
      `• Send a photo or video with the caption *${p}fotomenu* (or reply to a photo with *${p}fotomenu*).`,
      '• To change the image, just do it again with another one.',
      '',
      '*3. Bot name and photo*',
      `• Name: *${p}nomebot New Name*`,
      `• Profile photo: send a photo with the caption *${p}fotobot* (or reply to a photo with *${p}fotobot*).`,
      '',
      '*4. Prefix (the symbol before commands)*',
      `• *${p}setprefix !* changes it to *!*. Then commands become *!menu*, *!fotomenu*...`,
      '• */* always works too, in case you forget the prefix.',
      '',
      '*5. Sub-owners (people who help you)*',
      `• Add: *${p}addsubdono @person* (or the number with country code)`,
      `• Remove: *${p}delsubdono @person*`,
      `• See the list: *${p}subdonos*`,
      '',
      '*6. Free Fire and language*',
      `• Give someone autolike: *${p}addvip @person*`,
      `• ID limit per person: *${p}configurarff 3* (*0* = no limit)`,
      `• Group language: *${p}idioma pt*, *${p}idioma es* or *${p}idioma en*`,
      '',
      '*7. Menus*',
      `• *${p}menudono*: all your owner commands.`,
      `• *${p}menu*: the menu everyone sees.`,
      '',
      'Menu image, name, photo, prefix and sub-owners apply only to your bot. ID limit and language apply only to the group where you sent the command.'
    ]
  }
  return (textos[marca?.idioma] || textos.pt).join('\n')
}
